#!/usr/bin/env python3

"""

Step 3: build the training corpus.


Streams codeparrot-clean, keeps only permissively licensed, parseable,

non-autogenerated Python files, removes near-duplicates, and stops once the

estimated token budget is reached.


Outputs:

  data/corpus.jsonl   one JSON object per kept file (content + provenance)

  data/corpus_stats.json   filter counts and license mix (for the data sheet)


Usage:

  python build_corpus.py --target-tokens 340000000

"""


import argparse

import ast

import hashlib

import json

import os

import re

import sys

from collections import Counter


from datasets import load_dataset

from tqdm import tqdm


# Permissive only. GPL/AGPL/LGPL are dropped; the report explains why.

PERMISSIVE = {

    "mit",

    "apache-2.0",

    "bsd-3-clause",

    "bsd-2-clause",

    "unlicense",

    "isc",

    "bsd",

    "cc0-1.0",

}


# Rough BPE ratio for Python source, used only to decide when to stop.

CHARS_PER_TOKEN = 3.5


_WS = re.compile(r"[ \t]+")



def normalize(text: str) -> str:

    """Whitespace-insensitive view of a file, used for dedup only.


    Collapses runs of spaces/tabs and drops blank lines, so two copies of the

    same file that differ only in formatting hash identically. The ORIGINAL

    text is what gets written out; this is never used as training data.

    """

    lines = []

    for line in text.split("\n"):

        line = _WS.sub(" ", line).strip()

        if line:

            lines.append(line)

    return "\n".join(lines)



def main() -> int:

    ap = argparse.ArgumentParser()

    ap.add_argument("--dataset", default="codeparrot/codeparrot-clean")

    ap.add_argument("--split", default="train")

    ap.add_argument("--target-tokens", type=int, default=340_000_000)

    ap.add_argument("--min-chars", type=int, default=200)

    ap.add_argument("--max-chars", type=int, default=100_000)

    ap.add_argument("--out-dir", default="data")

    ap.add_argument(

        "--max-scanned",

        type=int,

        default=0,

        help="stop after scanning this many rows (0 = no limit); useful for smoke tests",

    )

    args = ap.parse_args()


    os.makedirs(args.out_dir, exist_ok=True)

    corpus_path = os.path.join(args.out_dir, "corpus.jsonl")

    stats_path = os.path.join(args.out_dir, "corpus_stats.json")


    target_chars = int(args.target_tokens * CHARS_PER_TOKEN)


    ds = load_dataset(args.dataset, split=args.split, streaming=True)


    seen_hashes = set()

    licenses = Counter()

    stats = Counter()

    kept_chars = 0


    bar = tqdm(total=target_chars, unit="char", unit_scale=True, desc="corpus")


    with open(corpus_path, "w", encoding="utf-8") as out:

        for row in ds:

            stats["scanned"] += 1


            if args.max_scanned and stats["scanned"] >= args.max_scanned:

                stats["stopped_on_scan_limit"] = 1

                break


            lic = (row.get("license") or "").lower()

            if lic not in PERMISSIVE:

                stats["drop_license"] += 1

                continue


            if row.get("autogenerated"):

                stats["drop_autogenerated"] += 1

                continue


            content = row.get("content") or ""

            n = len(content)

            if n < args.min_chars:

                stats["drop_too_small"] += 1

                continue

            if n > args.max_chars:

                stats["drop_too_large"] += 1

                continue


            # Must be real, parseable Python. This is what CoCoNuT failed.

            try:

                ast.parse(content)

            except (SyntaxError, ValueError, MemoryError, RecursionError):

                stats["drop_unparseable"] += 1

                continue


            h = hashlib.sha256(normalize(content).encode("utf-8")).hexdigest()

            if h in seen_hashes:

                stats["drop_duplicate"] += 1

                continue

            seen_hashes.add(h)


            out.write(

                json.dumps(

                    {

                        "content": content,

                        "repo_name": row.get("repo_name"),

                        "path": row.get("path"),

                        "license": lic,

                        "norm_hash": h,

                        "chars": n,

                    }

                )

                + "\n"

            )


            stats["kept"] += 1

            licenses[lic] += 1

            kept_chars += n

            bar.update(n)


            if kept_chars >= target_chars:

                stats["stopped_on_target"] = 1

                break


    bar.close()


    summary = {

        "dataset": args.dataset,

        "split": args.split,

        "target_tokens": args.target_tokens,

        "chars_per_token_assumed": CHARS_PER_TOKEN,

        "kept_files": stats["kept"],

        "kept_chars": kept_chars,

        "estimated_tokens": int(kept_chars / CHARS_PER_TOKEN),

        "filters": dict(stats),

        "licenses": dict(licenses.most_common()),

        "min_chars": args.min_chars,

        "max_chars": args.max_chars,

    }


    with open(stats_path, "w", encoding="utf-8") as f:

        json.dump(summary, f, indent=2)


    print(json.dumps(summary, indent=2))

    print(f"\nwrote {corpus_path}")

    print(f"wrote {stats_path}")

    return 0



if __name__ == "__main__":

    sys.exit(main())
